void
Begin3D(void)
{
	if(scopeOpen)
		return;
	scopeOpen = true;
	VitaGLBenchScope3D(true);
	if(viewportScale < 1.0f && GLReady()){
		// vitaGL: bottom-left corner of the display, applied immediately
		int w = (int)(SCREEN_W * viewportScale + 0.5f);
		int h = (int)(SCREEN_H * viewportScale + 0.5f);
		glViewport(0, 0, w < 1 ? 1 : w, h < 1 ? 1 : h);
		viewportChanged = true;
	}
}

void
End3D(void)
{
	if(!scopeOpen)
		return;
	scopeOpen = false;
	VitaGLBenchScope3D(false);
	if(viewportChanged){
		// librw caches the full-screen viewport: make it true again.
		glViewport(0, 0, SCREEN_W, SCREEN_H);
		viewportChanged = false;
	}
}

