// ---- CPU load probe -----------------------------------------------------------

// Hardware runs showed "--" for every core without saying why: log what the
// call returns, and accept both mask layouts (bit i, or the affinity layout
// SCE_KERNEL_CPU_MASK_USER_0 << i).
static bool cpuLoadOk, cpuProbeChecked;
static SceKernelSystemInfo cpuProbe;
static uint64_t cpuProbeTime;
static char cpuNote[64] = "cpu=untested";

static int
ReadSystemInfo(SceKernelSystemInfo *info)
{
	memset(info, 0, sizeof(*info));
	info->size = sizeof(*info);
	return sceKernelGetSystemInfo(info);
}

static bool
CoreValid(const SceKernelSystemInfo &info, int i)
{
	if(info.activeCpuMask & ((1U << i) | (0x10000U << i)))
		return true;
	return info.activeCpuMask == 0 && info.cpuInfo[i].idleClock != 0;
}

static void
LogSystemInfo(const char *when, int rc, const SceKernelSystemInfo &info)
{
	printf("[BENCH] cpu probe %s: rc=0x%08X mask=0x%08X idle_us=%llu/%llu/%llu/%llu\n", when, (unsigned)rc,
	       (unsigned)info.activeCpuMask, (unsigned long long)info.cpuInfo[0].idleClock,
	       (unsigned long long)info.cpuInfo[1].idleClock, (unsigned long long)info.cpuInfo[2].idleClock,
	       (unsigned long long)info.cpuInfo[3].idleClock);
}

static void
ProbeCpuLoad(void)
{
	int rc = ReadSystemInfo(&cpuProbe);
	cpuProbeTime = VitaPerfNow();
	LogSystemInfo("init", rc, cpuProbe);
	cpuLoadOk = false;
	if(rc >= 0)
		for(int i = 0; i < 4; i++)
			if(CoreValid(cpuProbe, i))
				cpuLoadOk = true;
	snprintf(cpuNote, sizeof(cpuNote), "cpu=%s rc=0x%X mask=0x%X", cpuLoadOk ? "probing" : "no",
	         (unsigned)rc, (unsigned)cpuProbe.activeCpuMask);
}

// A few seconds later: idle clocks must have moved on at least one core.
static void
CheckCpuLoad(uint64_t now)
{
	if(cpuProbeChecked || !cpuLoadOk || now - cpuProbeTime < 2000000)
		return;
	cpuProbeChecked = true;
	SceKernelSystemInfo info;
	int rc = ReadSystemInfo(&info);
	LogSystemInfo("recheck", rc, info);
	bool moved = false;
	if(rc >= 0)
		for(int i = 0; i < 4; i++)
			if(CoreValid(info, i) && info.cpuInfo[i].idleClock > cpuProbe.cpuInfo[i].idleClock)
				moved = true;
	cpuLoadOk = moved;
	snprintf(cpuNote, sizeof(cpuNote), "cpu=%s rc=0x%X mask=0x%X", moved ? "ok" : "static",
	         (unsigned)rc, (unsigned)info.activeCpuMask);
	if(!moved)
		printf("[BENCH] cpu load unavailable: idle clocks did not move\n");
}

// ---- GPU fence ------------------------------------------------------------------

enum { FENCE_UNKNOWN, FENCE_PROBING, FENCE_OK, FENCE_FAILED };
static int fenceState;
static const char *fenceWhy = "GL not ready";
static volatile unsigned int *fenceAddress;
static uint32_t probeTarget, lastTarget;
static uint64_t probeStart;

static void
FenceFail(const char *why)
{
	fenceState = FENCE_FAILED;
	fenceWhy = why;
	printf("[BENCH] GPU fence unavailable: %s (address=%p value=%u region=%p)\n", why,
	       (void*)query_fence.address, query_fence.value, GLReady() ? (void*)sceGxmGetNotificationRegion() : nullptr);
}

// Non-blocking, main thread. The fence is trusted once the GPU has written a
// value that the CPU submitted after vitaGL reset it to 0.
static int
CheckFence(void)
{
	if(fenceState == FENCE_OK || fenceState == FENCE_FAILED || !GLReady())
		return fenceState;
	if(query_fence.address == nullptr){
		if(query_fence.value)
			FenceFail("scenes submitted with no notification address");
		return fenceState;
	}
	if(fenceState == FENCE_UNKNOWN){
		volatile unsigned int *region = sceGxmGetNotificationRegion();
		volatile unsigned int *address = query_fence.address;
		if(region == nullptr || address < region || address >= region + NOTIFICATION_WORDS){
			FenceFail("address outside the GXM notification region");
			return fenceState;
		}
		if(query_fence.value == 0)
			return fenceState;	// nothing submitted yet
		fenceAddress = address;
		probeTarget = query_fence.value;
		probeStart = VitaPerfNow();
		fenceState = FENCE_PROBING;
		fenceWhy = "probing";
	}
	uint32_t reached = *fenceAddress;
	if((int32_t)(reached - query_fence.value) > 0)
		FenceFail("GPU value ahead of the submitted value");
	else if((int32_t)(reached - probeTarget) >= 0){
		fenceState = FENCE_OK;
		fenceWhy = "ok";
		printf("[BENCH] GPU fence ok: value %u reached %.1f ms after the probe\n",
		       probeTarget, (VitaPerfNow() - probeStart) / 1000.0);
	}else if(VitaPerfNow() - probeStart > 3000000)
		FenceFail("no progress in 3 s");
	return fenceState;
}

// Caps(): decide now if the GPU has work in flight (a few ms at most).
static int
WaitFence(uint64_t timeoutUs)
{
	uint64_t start = VitaPerfNow();
	while(CheckFence() == FENCE_PROBING && VitaPerfNow() - start < timeoutUs)
		sceKernelDelayThread(1000);
	return fenceState;
}

// Frames waiting for the GPU (main thread -> poller) and completed frames
// (poller -> main thread): single producer, single consumer rings.
#define GPU_RING 64
struct PendingFrame {
	uint32_t frame, target;
	uint64_t submitUs, doneUs;	// doneUs != 0: already known (GPU sync mode)
};
struct DoneFrame {
	uint32_t frame;
	uint64_t doneUs;
};
static PendingFrame pending[GPU_RING];
static DoneFrame done[GPU_RING];
static std::atomic<uint32_t> pendingHead, pendingTail, doneHead, doneTail;
static std::atomic<bool> pollerSleeping;
static std::atomic<uint32_t> gpuQueueFull, gpuDoneFull, gpuTimeouts;
static uint32_t gpuQueueFullSeen, gpuDoneFullSeen, gpuTimeoutsSeen;
static SceUID pollerWake = -1, poller = -1;

static void
PushDone(uint32_t frame, uint64_t doneUs)
{
	uint32_t head = doneHead.load(std::memory_order_relaxed);
	if(head - doneTail.load(std::memory_order_acquire) >= GPU_RING){
		gpuDoneFull.fetch_add(1, std::memory_order_relaxed);
		return;
	}
	done[head % GPU_RING].frame = frame;
	done[head % GPU_RING].doneUs = doneUs;
	doneHead.store(head + 1, std::memory_order_release);
}

// Sleeps on a semaphore while nothing is pending, otherwise polls the
// notification every 150 us: completion times are within ~0.2 ms.
static int
GpuPoller(SceSize, void *)
{
	VitaPerfRegisterThread("BenchGpuFence");
	for(;;){
		uint32_t tail = pendingTail.load(std::memory_order_relaxed);
		if(tail == pendingHead.load()){
			pollerSleeping.store(true);
			if(tail == pendingHead.load()){
				SceUInt timeout = 100000;
				sceKernelWaitSema(pollerWake, 1, &timeout);
			}
			pollerSleeping.store(false);
			continue;
		}
		const PendingFrame &p = pending[tail % GPU_RING];
		uint64_t now = VitaPerfNow();
		if(p.doneUs || (int32_t)(*fenceAddress - p.target) >= 0){
			PushDone(p.frame, p.doneUs ? p.doneUs : now);
			pendingTail.store(tail + 1, std::memory_order_release);
		}else if(now - p.submitUs > 1000000){
			gpuTimeouts.fetch_add(1, std::memory_order_relaxed);
			pendingTail.store(tail + 1, std::memory_order_release);
		}else
			sceKernelDelayThread(150);
	}
	return 0;
}

static void
StartPoller(void)
{
	// Another user core than the main thread's, just above its priority so a
	// completion is seen promptly; each wake-up only costs a few microseconds.
	SceUID self = sceKernelGetThreadId();
	int mainMask = sceKernelGetThreadCpuAffinityMask(self);
	int mainPriority = sceKernelGetThreadCurrentPriority();
	SceKernelThreadInfo info;
	memset(&info, 0, sizeof(info));
	info.size = sizeof(info);
	int infoResult = sceKernelGetThreadInfo(self, &info);
	int mask = mainMask == SCE_KERNEL_CPU_MASK_USER_2 ? SCE_KERNEL_CPU_MASK_USER_1 : SCE_KERNEL_CPU_MASK_USER_2;
	int priority = mainPriority >= 64 + 8 && mainPriority <= 191 ? mainPriority - 8 : 0x10000100;
	pollerWake = sceKernelCreateSema("reLCS bench GPU wake", 0, 0, 1, nullptr);
	if(pollerWake >= 0)
		poller = sceKernelCreateThread("reLCS bench GPU fence", GpuPoller, priority, 16 * 1024, 0, mask, nullptr);
	if(poller >= 0 && sceKernelStartThread(poller, 0, nullptr) < 0){
		sceKernelDeleteThread(poller);
		poller = -1;
	}
	printf("[BENCH] main thread: mask=0x%X priority=%d cpu=%d (info rc=0x%X); GPU poller: mask=0x%X priority=0x%X %s\n",
	       (unsigned)mainMask, mainPriority, infoResult >= 0 ? info.currentCpuId : -1, (unsigned)infoResult,
	       (unsigned)mask, (unsigned)priority, poller >= 0 ? "started" : "FAILED");
}

