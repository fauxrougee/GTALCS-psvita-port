bool
MakeDir(const char *path)
{
	char abs[256], dir[256];
	int len = snprintf(dir, sizeof(dir), "%s", AbsolutePath(path, abs, sizeof(abs)));
	if(len <= 0 || len >= (int)sizeof(dir))
		return false;
	while(len > 0 && dir[len - 1] == '/')
		dir[--len] = '\0';
	int rc = sceIoMkdir(dir, 0777);
	if(rc >= 0 || (unsigned)rc == ERRNO_EEXIST)
		return true;
	SceIoStat st;
	if(sceIoGetstat(dir, &st) >= 0 && SCE_S_ISDIR(st.st_mode))
		return true;
	printf("[BENCH] mkdir %s failed: 0x%08X\n", dir, (unsigned)rc);
	return false;
}

bool
WriteFile(const char *path, const void *data, uint32_t size)
{
	char abs[256];
	path = AbsolutePath(path, abs, sizeof(abs));
	SceUID fd = sceIoOpen(path, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_TRUNC, 0666);
	if(fd < 0){
		printf("[BENCH] cannot create %s: 0x%08X\n", path, (unsigned)fd);
		return false;
	}
	bool ok = WriteAll(fd, data, size);
	ok = sceIoClose(fd) >= 0 && ok;
	if(!ok)
		printf("[BENCH] write %s failed (%u bytes)\n", path, size);
	else{
		const char *name = strrchr(path, '/');
		// results.json after each test, summary.txt last in WriteResults
		const char *base = name ? name + 1 : path;
		if(strcmp(base, "results.json") == 0 || strcmp(base, "summary.txt") == 0)
			CopyLogNextTo(path);
	}
	return ok;
}

int
ReadSettingsFile(char *buf, int size)
{
	if(size <= 0)
		return -1;
	buf[0] = '\0';
	SceUID fd = sceIoOpen(VITA_DATA_DIR "benchmark.ini", SCE_O_RDONLY, 0);
	if(fd < 0)
		return -1;
	int total = 0;
	while(total < size - 1){
		int n = sceIoRead(fd, buf + total, size - 1 - total);
		if(n <= 0)
			break;
		total += n;
	}
	sceIoClose(fd);
	buf[total] = '\0';
	return total;
}

