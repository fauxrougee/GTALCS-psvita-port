static void
AddThread(BenchThreadTimes *out, const char *name, uint64_t runUs)
{
	if(out->count >= BENCH_MAX_THREADS)
		return;
	snprintf(out->name[out->count], sizeof(out->name[0]), "%s", name);
	out->runUs[out->count] = runUs;
	out->count++;
}

void
ReadThreadTimes(BenchThreadTimes *out)
{
	memset(out, 0, sizeof(*out));
	int n = VitaPerfThreadCount();
	for(int i = 0; i < n; i++){
		const char *name;
		uint64_t run;
		if(VitaPerfThreadRunTime(i, &name, &run))
			AddThread(out, name, run);
	}
	// vitaGL's garbage collector (resource frees, handshake in vglSwapBuffers)
	static int gcState;	// 0 untested, 1 ok, -1 unavailable
	if(gcState < 0 || !GLReady() || gc_thread <= 0)
		return;
	SceKernelThreadInfo info;
	memset(&info, 0, sizeof(info));
	info.size = sizeof(info);
	int rc = sceKernelGetThreadInfo(gc_thread, &info);
	if(gcState == 0){
		gcState = rc >= 0 ? 1 : -1;
		printf("[BENCH] vitaGL GC thread 0x%X: %s (rc=0x%X)\n", (unsigned)gc_thread,
		       rc >= 0 ? "readable" : "unavailable", (unsigned)rc);
	}
	if(rc >= 0)
		AddThread(out, "vitaGL GC", info.runClocks);
}

void
ReadCpuLoad(BenchCpuLoad *out)
{
	memset(out, 0, sizeof(*out));
	if(!cpuLoadOk)
		return;
	SceKernelSystemInfo info;
	if(ReadSystemInfo(&info) < 0)
		return;
	out->wallUs = VitaPerfNow();
	// Core 3 belongs to the system; report the valid cores from core 0 up.
	for(int i = 0; i < 4 && CoreValid(info, i); i++){
		out->idleUs[i] = info.cpuInfo[i].idleClock;
		out->cores = i + 1;
	}
}

void
FrameSubmitted(uint32_t frame)
{
	// A frame that skipped End3D must not carry its experiments into the next one.
	if(scopeOpen)
		End3D();
	uint64_t knownDone = 0;
	lastSyncUs = 0;
	if(gpuSync && GLReady()){
		// No scene is open right after vglSwapBuffers (BeginScene is deferred to
		// the next draw), so this only waits; glFinish would restart a scene.
		uint64_t start = VitaPerfNow();
		sceGxmFinish(gxm_context);
		knownDone = VitaPerfNow();
		uint64_t wait = knownDone - start;
		lastSyncUs = wait > 0xFFFFFFFFu ? 0xFFFFFFFFu : (uint32_t)wait;
	}
	if(CheckFence() != FENCE_OK)
		return;
	uint32_t target = query_fence.value;
	if(target == lastTarget)
		return;		// nothing new reached the GPU in this frame
	lastTarget = target;
	uint32_t head = pendingHead.load(std::memory_order_relaxed);
	if(head - pendingTail.load(std::memory_order_acquire) >= GPU_RING){
		gpuQueueFull.fetch_add(1, std::memory_order_relaxed);
		return;
	}
	PendingFrame &p = pending[head % GPU_RING];
	p.frame = frame;
	p.target = target;
	p.submitUs = VitaPerfNow();
	p.doneUs = knownDone;
	pendingHead.store(head + 1);
	if(pollerSleeping.load())
		sceKernelSignalSema(pollerWake, 1);
}

bool
PollGpuDone(uint32_t *frame, uint64_t *doneUs)
{
	uint32_t tail = doneTail.load(std::memory_order_relaxed);
	if(tail == doneHead.load(std::memory_order_acquire))
		return false;
	*frame = done[tail % GPU_RING].frame;
	*doneUs = done[tail % GPU_RING].doneUs;
	doneTail.store(tail + 1, std::memory_order_release);
	return true;
}

