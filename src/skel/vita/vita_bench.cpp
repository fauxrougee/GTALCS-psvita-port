{
	VitaPerfSceneWindowEnd(scene);
	uint32_t full = gpuQueueFull.load(), doneFull = gpuDoneFull.load(), timeouts = gpuTimeouts.load();
	if(full != gpuQueueFullSeen || doneFull != gpuDoneFullSeen || timeouts != gpuTimeoutsSeen)
		printf("[BENCH] GPU fence losses: queue_full=%u done_full=%u timeouts=%u (cumulative)\n",
		       full, doneFull, timeouts);
	gpuQueueFullSeen = full;
	gpuDoneFullSeen = doneFull;
	gpuTimeoutsSeen = timeouts;
}

