static unsigned swapsTotal, swapsAtIdleEnd;

// Previous gameplay frame, while frames follow each other without a break
static bool havePrevious;
static uint64_t prevSwapEnd, prevIdleBegin, prevIdleEnd, pendingReportUs;
static uint32_t prevGameTime;
static bool prevPaused;

// Current window: consecutive gameplay frames only
static uint64_t windowStart, lastGameEnd;
static unsigned gameFrames;
static VitaSampleSeries intervals, workTimes, latencies;
static uint32_t scratch[VitaSampleSeries::CAPACITY];
static uint64_t workSum, swapSum, waitSum, postSum, reportCost;
static uint32_t swapMax;
static uint64_t gameMsSum, realUsSum;
static unsigned clampedFrames, pausedFrames;
static VitaHoldHistogram holds;
static unsigned flipsGame, unmatchedSeen;
static uint32_t flipsLostSeen;
static unsigned excludedMenu, excludedLoad, excludedNoSwap, outsideSwaps;
// Baselines taken at the window's first frame
static SceKernelSystemInfo cpuBaseline;
static bool cpuBaselineValid;
static uint64_t sampleTime;
static size_t poolMinFree[4];
static unsigned heapMaxUsed;
static const vglMemType pools[4] = { VGL_MEM_RAM, VGL_MEM_VRAM, VGL_MEM_PHYCONT, VGL_MEM_BUDGET };
static const char *poolNames[4] = { "ram", "cdram", "phycont", "budget" };

static void
DrainFlips(void)
{
	uint32_t head = flipHead.load(std::memory_order_acquire);
	uint32_t tail = flipTail.load(std::memory_order_relaxed);
	for(; tail != head; tail++){
		const Flip &f = flips[tail % FLIP_RING];
		if(matcher.Flip(f.index, f.vcount, f.time, &holds, &latencies))
			flipsGame++;
	}
	flipTail.store(tail, std::memory_order_release);
}

static void
SampleMemory(uint64_t now)
{
	if(now - sampleTime < 500000)
		return;
	sampleTime = now;
	for(int i = 0; i < 4; i++){
		size_t free = vglMemFree(pools[i]);
		if(free < poolMinFree[i]) poolMinFree[i] = free;
	}
	// Heap usage is sampled every 0.5 s by VitaRecordPresentedFrame.
	unsigned used = VitaGetPerformanceStats().heapUsed;
	if(used > heapMaxUsed) heapMaxUsed = used;
}

static void
StartWindow(uint64_t now)
{
	windowStart = now;
	gameFrames = 0;
	intervals.Reset();
	workTimes.Reset();
	latencies.Reset();
	workSum = swapSum = waitSum = postSum = reportCost = 0;
	swapMax = 0;
	gameMsSum = realUsSum = 0;
	clampedFrames = pausedFrames = 0;
	holds.Reset();
	flipsGame = 0;
	unmatchedSeen = matcher.Unmatched();
	flipsLostSeen = flipsLost.load(std::memory_order_relaxed);

	memset(&cpuBaseline, 0, sizeof(cpuBaseline));
	cpuBaseline.size = sizeof(cpuBaseline);
	cpuBaselineValid = sceKernelGetSystemInfo(&cpuBaseline) >= 0;
	int n = numThreads.load() < MAX_THREADS ? numThreads.load() : MAX_THREADS;
	for(int i = 0; i < n; i++)
		if(!ThreadRunTime(threads[i], &threads[i].baseline))
			threads[i].baseline = 0;
	allocCalls.store(0, std::memory_order_relaxed);
	allocBytes.store(0, std::memory_order_relaxed);
	freeCalls.store(0, std::memory_order_relaxed);
	diskReads.store(0); diskBytes.store(0); diskUs.store(0); diskMaxUs.store(0); diskQueueMax.store(0);
	syncWaits.store(0); syncUs.store(0); syncMaxUs.store(0);
	streamRequestedMax = 0;
	streamUsedPeak = 0;
	for(int i = 0; i < 4; i++)
		poolMinFree[i] = (size_t)-1;
	heapMaxUsed = 0;
	sampleTime = 0;
	if(PERIODIC_REPORTS)
		SampleMemory(now);
}

static const char *
LimitName(void)
{
	return "uncapped";
}

// A partial window ends at a phase change: its frame statistics stop at the
// last gameplay frame, while CPU, thread, storage and allocation rates run to
// `now` and include the tail (tail_ms) of the frame that ended the window.
static void
WriteReport(uint64_t now, bool partial)
{
	uint64_t start = VitaPerfNow();
	double secs = (lastGameEnd - windowStart) / 1000000.0;
	VitaSampleSummary frame, work, latency;
	intervals.Summarise(&frame, scratch);
	workTimes.Summarise(&work, scratch);
	latencies.Summarise(&latency, scratch);
	unsigned n = intervals.Count();
	const char *sceneKey = "", *sceneId = "";
#ifdef RELCS_BENCHMARK
	if(reportScene){
		sceneKey = " scene=";
		sceneId = reportScene;
	}
#endif

	// Same first line as the stable build, over gameplay frames only
	if(n)
		printf("[VITA] %.1f fps, %.1f ms/frame, swap (GPU wait) %.1f ms/frame\n",
		       1000.0 / frame.meanMs, frame.meanMs, swapSum / 1000.0 / n);
	printf("[PERF] window=%u build=%s phase=game frames=%u intervals=%u secs=%.2f limit=%s partial=%d tail_ms=%.1f%s%s\n",
	       windowIndex++, VITA_BUILD_ID, gameFrames, n, secs, LimitName(), partial, (now - lastGameEnd) / 1000.0,
	       sceneKey, sceneId);
	if(n){
		printf("[PERF] frame_ms mean=%.2f median=%.2f p95=%.2f p99=%.2f min=%.2f max=%.2f over33=%.1f%% over50=%.1f%% dropped=%u\n",
		       frame.meanMs, frame.medianMs, frame.p95Ms, frame.p99Ms, frame.minMs, frame.maxMs,
		       100.0 * frame.over33 / n, 100.0 * frame.over50 / n, intervals.Dropped());
		if(frame.fpsWindows)
			printf("[PERF] fps_1s min=%.1f max=%.1f windows=%u\n", frame.fpsMin, frame.fpsMax, frame.fpsWindows);
		else
			printf("[PERF] fps_1s windows=0\n");
		printf("[PERF] split_ms work=%.2f work_p95=%.2f work_max=%.2f swap=%.2f swap_max=%.2f wait=%.2f post=%.2f report_included=%.2f\n",
		       workSum / 1000.0 / n, work.p95Ms, work.maxMs, swapSum / 1000.0 / n, swapMax / 1000.0,
		       waitSum / 1000.0 / n, postSum / 1000.0 / n, reportCost / 1000.0);
		printf("[PERF] gametime game_per_real=%.4f clamped=%u paused=%u\n",
		       realUsSum ? gameMsSum * 1000.0 / realUsSum : 0.0, clampedFrames, pausedFrames);
	}
	printf("[PERF] present flips=%u held_1/2/3/4+=%u/%u/%u/%u display_fps=%.1f",
	       flipsGame, holds.held[0], holds.held[1], holds.held[2], holds.held[3], holds.DisplayFPS());
	if(latency.count)
		printf(" latency_ms mean=%.2f p95=%.2f max=%.2f", latency.meanMs, latency.p95Ms, latency.maxMs);
	printf(" unmatched=%u lost=%u estimate=pre_flip_callback\n", matcher.Unmatched() - unmatchedSeen, flipsLost.load(std::memory_order_relaxed) - flipsLostSeen);
	printf("[PERF] excluded menu=%u load=%u noswap=%u outside_swaps=%u\n",
	       excludedMenu, excludedLoad, excludedNoSwap, outsideSwaps);
	excludedMenu = excludedLoad = excludedNoSwap = outsideSwaps = 0;

	// CPU load per core and thread run time, over the window's wall time
	double wall = (double)(now - windowStart);
	printf("[PERF] cpu_pct");
	SceKernelSystemInfo cpu;
	memset(&cpu, 0, sizeof(cpu));
	cpu.size = sizeof(cpu);
	bool haveCPU = cpuBaselineValid && wall > 0 && sceKernelGetSystemInfo(&cpu) >= 0;
	for(int i = 0; i < 4; i++){
		if(haveCPU && (cpu.activeCpuMask & cpuBaseline.activeCpuMask & (1U << i)) &&
		   cpu.cpuInfo[i].idleClock >= cpuBaseline.cpuInfo[i].idleClock){
			double load = 100.0 * (1.0 - (cpu.cpuInfo[i].idleClock - cpuBaseline.cpuInfo[i].idleClock) / wall);
			printf(" core%d=%.0f", i, load < 0.0 ? 0.0 : load > 100.0 ? 100.0 : load);
		}else
			printf(" core%d=--", i);
	}
	printf(" threads_ms_per_s");
	int nt = numThreads.load() < MAX_THREADS ? numThreads.load() : MAX_THREADS;
	for(int i = 0; i < nt; i++){
		SceUInt64 run;
		if(wall > 0 && threads[i].baseline && ThreadRunTime(threads[i], &run))
			printf(" %s=%.0f", threads[i].name, (run - threads[i].baseline) * 1000.0 / wall);
	}
	printf("\n");

#ifdef RELCS_BENCHMARK
	if(!periodicReports){
		// Not sampled during the frames of the window: once, now.
		VitaSampleMemoryNow();
		sampleTime = 0;
	}
#endif
	SampleMemory(now);
	printf("[PERF] mem_mib heap_used_max=%.1f/%.0f", heapMaxUsed / 1048576.0,
	       VitaGetPerformanceStats().heapTotal / 1048576.0);
	for(int i = 0; i < 4; i++)
		printf(" %s_free_min=%.1f/%.0f", poolNames[i],
		       poolMinFree[i] == (size_t)-1 ? 0.0 : poolMinFree[i] / 1048576.0, vglMemTotal(pools[i]) / 1048576.0);
	printf(" stream_used_peak=%.1f/%.1f stream_requested_max=%d\n",
	       streamUsedPeak / 1048576.0, streamAvailable / 1048576.0, streamRequestedMax);

	double perSec = wall > 0 ? 1000000.0 / wall : 0.0;
	uint32_t reads = diskReads.load(), waits = syncWaits.load();
	printf("[PERF] disk reads=%u kib=%.0f read_ms=%.1f read_max_ms=%.1f queue_max=%u sync_waits=%u sync_ms=%.1f sync_max_ms=%.1f\n",
	       reads, diskBytes.load() / 1024.0, diskUs.load() / 1000.0, diskMaxUs.load() / 1000.0, diskQueueMax.load(),
	       waits, syncUs.load() / 1000.0, syncMaxUs.load() / 1000.0);
	printf("[PERF] alloc_per_s malloc=%.0f free=%.0f kib=%.0f (all threads)\n",
	       allocCalls.load() * perSec, freeCalls.load() * perSec, allocBytes.load() / 1024.0 * perSec);

	VitaProfReportSections(gameFrames);
	VitaGLProfReport(gameFrames);
	const VitaLogStats log = VitaLogGetStats();
	printf("[PERF] logger async=%d queued_kib=%.1f peak_kib=%.1f dropped_bytes=%u truncated=%u io_errors=%u writer_max_ms=%.2f (cumulative)\n",
	       log.running, log.queued / 1024.0, log.peak / 1024.0, log.dropped, log.truncated, log.errors, log.writeMaxUs / 1000.0);
	VitaFlushLog();

	lastReport = now;
	windowStart = 0;
	// Formatting/enqueueing still delays the next image: keep it in observed
	// FPS. Disk writes now belong to LogWriter, not to this main-thread cost.
	pendingReportUs += VitaPerfNow() - start;
}

// Outside gameplay (front end, loading screens): a heartbeat so the log shows
// the game is alive, without statistics mixing phases.
static void
WriteHeartbeat(uint64_t now, unsigned swaps)
{
	printf("[VITA] %.1f swaps/s outside gameplay (menu or loading)\n",
	       swaps * 1000000.0 / (now - lastReport));
	printf("[PERF] excluded menu=%u load=%u noswap=%u outside_swaps=%u\n",
	       excludedMenu, excludedLoad, excludedNoSwap, outsideSwaps);
	excludedMenu = excludedLoad = excludedNoSwap = outsideSwaps = 0;
	VitaProfReportSections(0);
	VitaGLProfReport(0);
	VitaFlushLog();
	lastReport = now;
}

// ---- Frame hooks ----------------------------------------------------------------

bool
VitaPerfFrameDue(bool limiter, bool vsync, float elapsedMs, int maxFPS)
{
	// No busy wait, sleep deadline or 30 FPS menu setting may gate gameplay.
	(void)limiter; (void)vsync; (void)elapsedMs; (void)maxFPS;
	return true;
}

int
VitaPerfSwapInterval(int interval)
{
	// Retain vsync without dividing the display refresh rate by two.
	return interval ? 1 : 0;
}

void
VitaPerfIdleBegin(bool menu)
{
	// Section and GL times since the last gameplay frame belong to other phases.
	VitaProfDiscardFrame();
	VitaGLProfDiscardFrame();
	if(swapsTotal != swapsAtIdleEnd){
		outsideSwaps += swapsTotal - swapsAtIdleEnd;
		havePrevious = false;
	}
	inIdle = true;
	idleMenu = menu;
	idleSwaps = 0;
	idleFirstSubmit = matcher.Submitted();
	idleBegin = VitaPerfNow();
}

void
VitaPerfSwapBegin(void)
{
	swapBegin = VitaPerfNow();
	matcher.Submit(swapBegin, inIdle ? VitaFlipMatcher::PENDING : VitaFlipMatcher::OTHER);
}

void
VitaPerfSwapEnd(void)
{
	swapEnd = VitaPerfNow();
	swapsTotal++;
	if(inIdle){
		idleSwaps++;
		return;
	}
	DrainFlips();
	// A swap outside Idle (loading screen between two Idles) ends the window.
	if(PERIODIC_REPORTS && windowStart)
		WriteReport(swapEnd, true);
	static unsigned swapsSinceReport;
	swapsSinceReport++;
	if(PERIODIC_REPORTS && swapEnd - lastReport >= settings.reportSeconds * 1000000ULL){
		WriteHeartbeat(swapEnd, swapsSinceReport);
		swapsSinceReport = 0;
	}
}

void
VitaPerfIdleEnd(uint32_t gameTimeMs, bool paused)
{
	uint64_t now = VitaPerfNow();
	bool gameplay = !idleMenu && idleSwaps == 1;
#ifdef RELCS_BENCHMARK
	// the benchmark opened its window mid-frame (possibly after a blocking
	// load): like the benchmark's own records, the window starts after it
	if(skipSceneFrame){
		skipSceneFrame = false;
		gameplay = false;
	}
#endif
	for(uint32_t i = idleFirstSubmit; i != matcher.Submitted(); i++)
		matcher.SetKind(i, gameplay ? VitaFlipMatcher::GAME : VitaFlipMatcher::OTHER);
	inIdle = false;
	swapsAtIdleEnd = swapsTotal;

	if(!gameplay){
		if(idleMenu) excludedMenu++;
		else if(idleSwaps == 0) excludedNoSwap++;
		else excludedLoad++;
		VitaProfDiscardFrame();
		VitaGLProfDiscardFrame();
		havePrevious = false;
		DrainFlips();
		// A phase change ends the gameplay window
		if(PERIODIC_REPORTS && windowStart)
			WriteReport(now, true);
		return;
	}

	VitaProfCommitFrame();
	VitaGLProfCommitFrame();
	if(!firstGameFrameLogged){
		firstGameFrameLogged = true;
		printf("[PERF] first gameplay frame %.2f s after process start\n", now / 1000000.0);
	}
	if(windowStart == 0)
		StartWindow(now);
	gameFrames++;
	lastGameEnd = now;
	if(havePrevious){
		// interval = post (previous frame, after its swap) + wait (limiter and
		// main loop) + work (Idle up to the swap) + swap
		uint64_t interval = swapEnd - prevSwapEnd;
		uint64_t wait = idleBegin - prevIdleEnd;
		reportCost += pendingReportUs;
		intervals.Add((uint32_t)interval);
		uint64_t work = swapBegin - idleBegin;
		workTimes.Add((uint32_t)work);
		workSum += work;
		uint64_t swap = swapEnd - swapBegin;
		swapSum += swap;
		if(swap > swapMax) swapMax = (uint32_t)swap;
		waitSum += wait;
		postSum += prevIdleEnd - prevSwapEnd;
		// CTimer::Update runs first in Idle: compare its progress with real time
		// (report writing included: the game clock counted it too). Steps above
		// 60 ms are clamped by CTimer, slowing the game down.
		uint64_t real = idleBegin - prevIdleBegin;
		if(paused || prevPaused)
			pausedFrames++;
		else{
			gameMsSum += gameTimeMs - prevGameTime;
			realUsSum += real;
			if(real > 60000) clampedFrames++;
		}
	}
	havePrevious = true;
	pendingReportUs = 0;
	prevSwapEnd = swapEnd;
	prevIdleEnd = now;
	prevIdleBegin = idleBegin;
	prevGameTime = gameTimeMs;
	prevPaused = paused;

	DrainFlips();
	if(PERIODIC_REPORTS){
		SampleMemory(now);
		if(now - windowStart >= settings.reportSeconds * 1000000ULL)
			WriteReport(now, false);
	}
}

