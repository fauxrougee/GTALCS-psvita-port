// The game reads reLCS.ini much later (and rewrites it keeping unknown keys);
// the GL entry points are chosen before that, so read [VitaPerf] directly.
static void
ReadSettings(void)
{
	FILE *f = fopen(VITA_DATA_DIR "reLCS.ini", "r");
	if(f == nullptr)
		return;
	char line[160];
	bool inSection = false;
	while(fgets(line, sizeof(line), f)){
		char *s = line;
		while(isspace((unsigned char)*s)) s++;
		char *end = s + strlen(s);
		while(end > s && isspace((unsigned char)end[-1])) *--end = '\0';
		if(*s == '['){
			inSection = strncasecmp(s, "[VitaPerf]", 10) == 0;
			continue;
		}
		char *eq = strchr(s, '=');
		if(!inSection || eq == nullptr)
			continue;
		*eq = '\0';
		for(char *k = eq; k > s && isspace((unsigned char)k[-1]); ) *--k = '\0';
		int value = atoi(eq + 1);
		// Ignore old FrameLimit=0/30/60 entries: installing this build must
		// actually unlock gameplay, even with a config from an earlier test.
		if(strcasecmp(s, "ReportSeconds") == 0)
			settings.reportSeconds = value < 1 ? 1 : value > 60 ? 60 : value;
		else if(strcasecmp(s, "GLCounters") == 0)
			settings.glCounters = value != 0;
	}
	fclose(f);
#ifdef RELCS_BENCHMARK
	// Draw modes and flat textures live in the counting wrappers (gl_vita.cpp).
	settings.glCounters = true;
#endif
}

// ---- Allocation counters (-Wl,--wrap=malloc,... in vita/CMakeLists.txt) --------

// Every thread; malloc/calloc/realloc/memalign and free, which includes C++ new
// and delete. newlib's internal _malloc_r users (stdio buffers) are not seen.
static std::atomic<uint32_t> allocCalls, allocBytes, freeCalls;
#ifdef RELCS_BENCHMARK
// Benchmark totals: the window counters are reset at each window start.
static std::atomic<uint32_t> totalAllocCalls, totalAllocBytes, totalFreeCalls;
static std::atomic<uint32_t> totalDiskReads, totalDiskBytes, totalDiskUs, totalSyncWaits, totalSyncUs;
#endif

extern "C" {
void *__real_malloc(size_t size);
void *__real_calloc(size_t n, size_t size);
void *__real_realloc(void *p, size_t size);
void *__real_memalign(size_t align, size_t size);
void __real_free(void *p);

static inline void
CountAlloc(size_t size)
{
	allocCalls.fetch_add(1, std::memory_order_relaxed);
	allocBytes.fetch_add((uint32_t)size, std::memory_order_relaxed);
#ifdef RELCS_BENCHMARK
	totalAllocCalls.fetch_add(1, std::memory_order_relaxed);
	totalAllocBytes.fetch_add((uint32_t)size, std::memory_order_relaxed);
#endif
}

void *__wrap_malloc(size_t size) { CountAlloc(size); return __real_malloc(size); }
void *__wrap_calloc(size_t n, size_t size) { CountAlloc(n * size); return __real_calloc(n, size); }
void *__wrap_realloc(void *p, size_t size) { CountAlloc(size); return __real_realloc(p, size); }
void *__wrap_memalign(size_t align, size_t size) { CountAlloc(size); return __real_memalign(align, size); }

void
__wrap_free(void *p)
{
	if(p){
		freeCalls.fetch_add(1, std::memory_order_relaxed);
#ifdef RELCS_BENCHMARK
		totalFreeCalls.fetch_add(1, std::memory_order_relaxed);
#endif
	}
	__real_free(p);
}
}

// ---- Storage, streaming and threads -------------------------------------------

static std::atomic<uint32_t> diskReads, diskBytes, diskUs, diskMaxUs, diskQueueMax;
static std::atomic<uint32_t> syncWaits, syncUs, syncMaxUs;
static int streamRequestedMax;
static uint32_t streamUsedPeak, streamAvailable;

static void
AtomicMax(std::atomic<uint32_t> &value, uint32_t x)
{
	uint32_t old = value.load(std::memory_order_relaxed);
	while(x > old && !value.compare_exchange_weak(old, x, std::memory_order_relaxed))
		;
}

void
VitaPerfDiskRead(uint32_t bytes, uint64_t us)
{
	diskReads.fetch_add(1, std::memory_order_relaxed);
	diskBytes.fetch_add(bytes, std::memory_order_relaxed);
	diskUs.fetch_add((uint32_t)us, std::memory_order_relaxed);
	AtomicMax(diskMaxUs, (uint32_t)us);
#ifdef RELCS_BENCHMARK
	totalDiskReads.fetch_add(1, std::memory_order_relaxed);
	totalDiskBytes.fetch_add(bytes, std::memory_order_relaxed);
	totalDiskUs.fetch_add((uint32_t)us, std::memory_order_relaxed);
#endif
}

void
VitaPerfDiskSync(uint64_t us)
{
	syncWaits.fetch_add(1, std::memory_order_relaxed);
	syncUs.fetch_add((uint32_t)us, std::memory_order_relaxed);
	AtomicMax(syncMaxUs, (uint32_t)us);
#ifdef RELCS_BENCHMARK
	totalSyncWaits.fetch_add(1, std::memory_order_relaxed);
	totalSyncUs.fetch_add((uint32_t)us, std::memory_order_relaxed);
#endif
}

void
VitaPerfDiskQueued(int depth)
{
	if(depth > 0)
		AtomicMax(diskQueueMax, (uint32_t)depth);
}

void
VitaPerfStreaming(int requested, uint32_t memoryUsed, uint32_t memoryAvailable)
{
	if(requested > streamRequestedMax) streamRequestedMax = requested;
	if(memoryUsed > streamUsedPeak) streamUsedPeak = memoryUsed;
	streamAvailable = memoryAvailable;
}

struct ThreadSlot {
	const char *name;
	SceUID thid;
	SceUInt64 baseline;
	std::atomic<bool> ready;
};
#define MAX_THREADS 8
static ThreadSlot threads[MAX_THREADS];
static std::atomic<int> numThreads;

void
VitaPerfRegisterThread(const char *name)
{
	int i = numThreads.fetch_add(1);
	if(i >= MAX_THREADS)
		return;
	threads[i].name = name;
	threads[i].thid = sceKernelGetThreadId();
	threads[i].ready.store(true, std::memory_order_release);
}

static bool
ThreadRunTime(ThreadSlot &t, SceUInt64 *run)
{
	if(!t.ready.load(std::memory_order_acquire))
		return false;
	SceKernelThreadInfo info;
	memset(&info, 0, sizeof(info));
	info.size = sizeof(info);
	if(sceKernelGetThreadInfo(t.thid, &info) < 0)
		return false;
	*run = info.runClocks;
	return true;
}

// ---- Presentation (vitaGL display queue) ------------------------------------------

// vitaGL calls the display callback on its display queue thread just before
// each flip. The callback only stores the flip; the main thread pairs it with
// its swap (VitaFlipMatcher) once it knows whether that was a gameplay frame.
// vcount steps give how long each image stayed on screen.
static VitaFlipMatcher matcher;

struct Flip {
	uint32_t index;
	int vcount;
	uint64_t time;
};
#define FLIP_RING 256
static Flip flips[FLIP_RING];
static std::atomic<uint32_t> flipHead, flipTail, flipsLost;

static void
OnDisplayFlip(void *)
{
	static uint32_t index;
	uint32_t head = flipHead.load(std::memory_order_relaxed);
	if(head - flipTail.load(std::memory_order_acquire) >= FLIP_RING){
		flipsLost.fetch_add(1, std::memory_order_relaxed);
		index++;
		return;
	}
	Flip &f = flips[head % FLIP_RING];
	f.index = index++;
	f.vcount = sceDisplayGetVcount();
	f.time = sceKernelGetProcessTimeWide();
	flipHead.store(head + 1, std::memory_order_release);
}

void
VitaPerfGLReady(void)
{
	vglSetDisplayCallback(OnDisplayFlip);
}

